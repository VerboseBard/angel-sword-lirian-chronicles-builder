// Writes src/js/crafting-points.js: the crafting HP ("crafting points") of every
// craftable item in the 0.13.2 rules data.
//
// Why this exists (task 033): the official item records carry `craftingPoints`
// (Bow (Two-Handed) 30, Axolotl Elixir 50, ...), but the per-version item data
// the builder ships (assets/versions/<version>/lyrian-data.js) does not, so the
// Crafting tab never knew an item's crafting HP. This file adds that one field
// without touching the audited per-version data files.
//
// Source: data/angelssword/decoded/item_details.json (rules 0.13.2). Only plain
// whole numbers are kept; the two placeholders in the source ("lol", "No") and
// the "-" on the materials card are left out.
//
// Run:  node scripts/gen-crafting-points.mjs          (rewrites the file)
//       node scripts/gen-crafting-points.mjs --check  (exit 1 if it is stale)
import path from "node:path";
import { fileURLToPath } from "node:url";
import { readFile, writeFile } from "node:fs/promises";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const details = JSON.parse(await readFile(path.join(root, "data/angelssword/decoded/item_details.json"), "utf8"));
const metadata = JSON.parse(await readFile(path.join(root, "data/angelssword/decoded/metadata.json"), "utf8"));
const version = metadata.latestVersion.versionNumber;

const normalizeSpace = (value) => String(value ?? "").replace(/\r\n/g, "\n").replace(/[ \t]+/g, " ").trim();
const entries = details
  .filter((entry) => normalizeSpace(entry.craftingType) && normalizeSpace(entry.craftingType) !== "-")
  .filter((entry) => /^\d+$/.test(normalizeSpace(entry.craftingPoints)))
  .map((entry) => [normalizeSpace(entry.name), normalizeSpace(entry.craftingPoints)])
  .sort((left, right) => left[0].localeCompare(right[0]));
const names = new Set(entries.map(([name]) => name));
if (names.size !== entries.length) {
  throw new Error("Two craftable items share a name; key the table by id instead.");
}

const lines = entries.map(([name, points]) => `  ${JSON.stringify(name)}: ${JSON.stringify(points)}`);
const text = `// Generated by scripts/gen-crafting-points.mjs from data/angelssword/decoded/item_details.json.
// Do not edit by hand: change the generator or the source data and run it again.
//
// The crafting HP ("crafting points") of each craftable item in rules ${version}.
// The per-version item data the builder ships does not carry this field (task 033),
// so buildLookup adds it from here for rules ${version} only. Other rules versions
// have no crafting HP data in the sheet and the Crafting tab says so.
export const CRAFTING_POINTS_VERSION = ${JSON.stringify(version)};

export const CRAFTING_POINTS_BY_ITEM_NAME = {
${lines.join(",\n")}
};

// Returns the item list with \`craftingPoints\` set where this table has the item.
// A record that already has its own \`craftingPoints\` keeps it.
export function withCraftingPoints(items, rulesVersion) {
  if (String(rulesVersion || "") !== CRAFTING_POINTS_VERSION || !Array.isArray(items)) {
    return items;
  }
  return items.map((item) => {
    const points = item && !item.craftingPoints ? CRAFTING_POINTS_BY_ITEM_NAME[item.name] : "";
    return points ? { ...item, craftingPoints: points } : item;
  });
}
`;
const target = path.join(root, "src/js/crafting-points.js");
if (process.argv.includes("--check")) {
  const current = await readFile(target, "utf8").catch(() => "");
  const same = current.replace(/\r\n/g, "\n") === text;
  console.log(same ? `crafting-points.js is current (${entries.length} items, rules ${version}).` : "crafting-points.js is stale: run node scripts/gen-crafting-points.mjs");
  process.exit(same ? 0 : 1);
}
await writeFile(target, text.replace(/\n/g, "\r\n"));
console.log(`Wrote src/js/crafting-points.js: ${entries.length} items, rules ${version}.`);
